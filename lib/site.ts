/**
 * site.ts — Site origin and per-page metadata (canonical URL, bn/en alternates, share cards).
 */
import 'server-only';
import type { Metadata } from 'next';
import { env } from './env';
import { defaultLocale, localePath, type Locale } from './i18n';

const SITE_NAME: Record<Locale, string> = { bn: 'কৃষিবাংলা', en: 'KrishiBangla' };
const OG_LOCALE: Record<Locale, string> = { bn: 'bn_BD', en: 'en_GB' };

/** Public origin: NEXT_PUBLIC_SITE_URL, else Vercel's production domain, else local dev. */
export function siteUrl(): URL {
  if (env.NEXT_PUBLIC_SITE_URL) return new URL(env.NEXT_PUBLIC_SITE_URL);
  if (env.VERCEL_PROJECT_PRODUCTION_URL) return new URL(`https://${env.VERCEL_PROJECT_PRODUCTION_URL}`);
  return new URL('http://localhost:3000');
}

/** Both language versions of a path, for <link rel="alternate" hreflang> and the sitemap. */
export function languageAlternates(path: string) {
  return { bn: localePath('bn', path), en: localePath('en', path), 'x-default': localePath(defaultLocale, path) };
}

// Generated by app/opengraph-image.tsx. It sits outside app/[locale], so pages reference it explicitly.
const SHARE_IMAGE = {
  url: '/opengraph-image',
  width: 1200,
  height: 630,
  alt: 'KrishiBangla — weather, irrigation advice, market prices and climate alerts for Bangladesh',
};

/** Title, description, canonical, hreflang alternates and Open Graph/Twitter fields for one page. */
export function pageMetadata(locale: Locale, path: string, { title, description }: { title: string; description?: string }): Metadata {
  const url = localePath(locale, path);
  return {
    title,
    description,
    alternates: { canonical: url, languages: languageAlternates(path) },
    openGraph: {
      title,
      description,
      url,
      siteName: SITE_NAME[locale],
      type: 'website',
      locale: OG_LOCALE[locale],
      alternateLocale: OG_LOCALE[locale === 'bn' ? 'en' : 'bn'],
      images: [SHARE_IMAGE],
    },
    twitter: { card: 'summary_large_image', title, description, images: [SHARE_IMAGE] },
  };
}
