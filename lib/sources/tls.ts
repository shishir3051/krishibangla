const CA = [...rootCertificates, SECTIGO_DV_R36];
const MAX_BYTES = 2 * 1024 * 1024;

/** GET a page over HTTPS with the extra intermediate; rejects on non-2xx, timeout or more than 2 MB. */
export function getText(url: string, timeoutMs = 20_000): Promise<string> {
  return new Promise((resolve, reject) => {
    const request = get(url, { ca: CA, timeout: timeoutMs }, (res) => {
      const status = res.statusCode ?? 0;
      if (status < 200 || status >= 300) {
        res.resume();
        reject(new Error(`${new URL(url).host} responded ${status}`));
        return;
      }
      const chunks: Buffer[] = [];
      let size = 0;
      res.on('data', (chunk: Buffer) => {
        size += chunk.length;
        if (size > MAX_BYTES) request.destroy(new Error(`${new URL(url).host} response is larger than 2 MB`));
        else chunks.push(chunk);
      });
      res.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
      res.on('error', reject);
    });
    request.on('timeout', () => request.destroy(new Error(`${new URL(url).host} timed out`)));
    request.on('error', reject);
  });
}
