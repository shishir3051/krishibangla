/**
 * build-map.mjs — Generates data/map/district-paths.json (SVG paths for the 64 districts).
 *
 *   node scripts/build-map.mjs          write the file
 *   node scripts/build-map.mjs --check  exit 1 if the committed file is out of date (for CI)
 *
 * Source: geoBoundaries gbOpen BGD ADM2 (BGD-ADM2-16705992; original data: Bangladesh Bureau of Statistics,
 * OCHA ROAP; licence CC BY 3.0 IGO), data/map/source/geoboundaries-bgd-adm2.geojson.
 * mapshaper is pinned in package.json so the simplification is reproducible.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { geoArea, geoMercator, geoPath } from 'd3-geo';
import mapshaper from 'mapshaper';

const root = fileURLToPath(new URL('..', import.meta.url));
const SOURCE = `${root}data/map/source/geoboundaries-bgd-adm2.geojson`;
const OUTPUT = `${root}data/map/district-paths.json`;
const WIDTH = 500;
const HEIGHT = 700;
const PADDING = 10;
const SIMPLIFY = '6%'; // share of vertices kept; keep-shapes stops small districts disappearing

const { districts } = JSON.parse(readFileSync(`${root}data/districts.json`, 'utf8'));
const slugByName = new Map(
  districts.flatMap((d) => [d.name.en, ...d.aliases].map((n) => [n.toLowerCase(), d.slug]))
);

const output = await mapshaper.applyCommands(
  `-i source.json -simplify ${SIMPLIFY} keep-shapes -o format=geojson precision=0.0001 out.json`,
  { 'source.json': readFileSync(SOURCE, 'utf8') }
);
const simplified = JSON.parse(output['out.json']);

// d3-geo is spherical and wants clockwise exterior rings; GeoJSON (RFC 7946) uses the opposite.
// A ring wound the "wrong" way covers the rest of the globe, so flip any shape larger than a hemisphere.
for (const feature of simplified.features) {
  if (geoArea(feature) > 2 * Math.PI) {
    const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
    for (const polygon of polygons) for (const ring of polygon) ring.reverse();
  }
}

const projection = geoMercator().fitExtent(
  [
    [PADDING, PADDING],
    [WIDTH - PADDING, HEIGHT - PADDING],
  ],
  simplified
);
const path = geoPath(projection).digits(1);

// Rounding to 0.1 px leaves runs of identical points ("L1,2L1,2"); drop the repeats.
function dedupe(d) {
  let prev = '';
  return d.replace(/([MLZ])([^MLZ]*)/g, (seg, cmd, xy) => {
    if (cmd === 'L' && xy === prev) return '';
    prev = cmd === 'Z' ? '' : xy;
    return seg;
  });
}

const shapes = simplified.features.map((feature) => {
  const name = feature.properties.shapeName;
  const slug = slugByName.get(name.toLowerCase());
  if (!slug) throw new Error(`No registry district for GeoJSON shape "${name}"`);
  const [cx, cy] = path.centroid(feature).map((v) => Math.round(v * 10) / 10);
  return { slug, d: dedupe(path(feature)), cx, cy };
});

if (new Set(shapes.map((s) => s.slug)).size !== districts.length) {
  throw new Error(`Expected ${districts.length} unique districts, got ${shapes.length}`);
}

const json =
  JSON.stringify(
    {
      $comment:
        'Generated by scripts/build-map.mjs from geoBoundaries gbOpen BGD ADM2 (BBS, OCHA ROAP; CC BY 3.0 IGO). Do not edit by hand.',
      viewBox: `0 0 ${WIDTH} ${HEIGHT}`,
      districts: shapes.sort((a, b) => a.slug.localeCompare(b.slug)),
    },
    null,
    1
  ) + '\n';

if (process.argv.includes('--check')) {
  const current = readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n');
  if (current !== json) {
    console.error('data/map/district-paths.json is out of date — run: node scripts/build-map.mjs');
    process.exit(1);
  }
  console.log('district-paths.json is up to date');
} else {
  writeFileSync(OUTPUT, json);
  console.log(`wrote ${shapes.length} districts, ${(json.length / 1024).toFixed(0)} KB`);
}
